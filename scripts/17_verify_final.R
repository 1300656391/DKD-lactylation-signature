chk <- function(yy, s, label) {
  r <- roc(yy, s, quiet = TRUE)
  ci <- coords(r, "best", ret = c("sensitivity", "specificity"), best.method = "youden")
  ok <- isTRUE(all.equal(round(as.numeric(auc(r)), 9), round(ref_auc, 9))) &&
        isTRUE(all.equal(round(unname(ci$sensitivity), 6), round(ref_sens, 6))) &&
        isTRUE(all.equal(round(unname(ci$specificity), 6), round(ref_spec, 6)))
  lines <<- c(lines, sprintf("%-16s AUC=%.6f sens=%.6f spec=%.6f  vs refs %.6f/%.6f/%.6f  %s",
                             label, auc(r), ci$sensitivity, ci$specificity,
                             ref_auc, ref_sens, ref_spec, ifelse(ok, "MATCH", "MISMATCH")))
  ok
}
