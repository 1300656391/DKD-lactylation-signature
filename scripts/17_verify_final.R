zrows <- function(m) t(apply(m, 1, function(r) (r - mean(r)) / sd(r)))
sc <- function(e) {
  hg <- intersect(hub, rownames(e))
  Xv <- t(zrows(e[hg, , drop = FALSE]))
  as.vector(Xv %*% bh[hg] + bh[["(Intercept)"]])
}
